-- Admin RBAC System Migration
-- Implements role-based access control for admin functionality
-- Following official Supabase RBAC pattern with Auth Hooks

-- Custom types for roles and permissions
CREATE TYPE public.app_role AS ENUM ('admin', 'user');
CREATE TYPE public.app_permission AS ENUM (
  'content.moderate',     -- Manage flagged content
  'premium.manage',       -- Manage premium listings  
  'analytics.view',       -- View admin dashboard and analytics
  'system.manage'         -- System-level admin functions
);

-- User roles table
CREATE TABLE public.user_roles (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id   uuid REFERENCES auth.users ON DELETE CASCADE NOT NULL,
  role      app_role NOT NULL,
  created_at timestamp with time zone DEFAULT NOW() NOT NULL,
  updated_at timestamp with time zone DEFAULT NOW() NOT NULL,
  UNIQUE (user_id, role)
);

COMMENT ON TABLE public.user_roles IS 'Application roles for each user (admin/user)';

-- Role permissions table
CREATE TABLE public.role_permissions (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role         app_role NOT NULL,
  permission   app_permission NOT NULL,
  created_at   timestamp with time zone DEFAULT NOW() NOT NULL,
  UNIQUE (role, permission)
);

COMMENT ON TABLE public.role_permissions IS 'Permissions assigned to each role';

